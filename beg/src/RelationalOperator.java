
public class RelationalOperator {
    public static void main(String[] args) {
        int a = 40;
        int b = 60;
        System.out.println(a==b);
        System.out.println(a != b);
        System.out.println( a > b);
        System.out.println(a >= b);
        System.out.println(true);
    }
}
